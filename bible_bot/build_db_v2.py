def get_text(elem):
    return ''.join(elem.itertext()).strip()

# Удаляем старую базу и создаем новую
import os
if os.path.exists('bible.db'):
    os.remove('bible.db')

conn = sqlite3.connect('bible.db')
cursor = conn.cursor()

cursor.execute('''
    CREATE TABLE verses (
        id INTEGER PRIMARY KEY AUTOINCREMENT,
        book TEXT,
        book_order INTEGER,
        chapter INTEGER,
        verse_num INTEGER,
        text TEXT
    )
''')
cursor.execute('CREATE INDEX idx_book ON verses (book)')
cursor.execute('CREATE INDEX idx_order ON verses (book_order, chapter)')

print("Читаем и очищаем структуру FB2...")
tree = ET.parse('bible.fb2')
root = tree.getroot()
body = root.find(f'{NS}body')

total_verses = 0

for testament in body.findall(f'{NS}section'):
    for book_section in testament.findall(f'{NS}section'):
        book_title_elem = book_section.find(f'{NS}title')
        if book_title_elem is None:
            continue
            
        raw_name = get_text(book_title_elem)
        
        # 🧹 ОЧИСТКА: заменяем все переносы строк и множественные пробелы на один пробел
        clean_name = re.sub(r'\s+', ' ', raw_name).strip()
        
        # 🧹 ОЧИСТКА: исправляем латинскую 'c' на русскую 'с' в слове Екклесиаста
        clean_name = clean_name.replace('Екклеcиаста', 'Екклесиаста')
        
        # Получаем порядок, если книги нет в словаре — ставим 999
        order = BOOK_ORDER.get(clean_name, 999)
        
        for chapter_section in book_section.findall(f'{NS}section'):
            chapter_title_elem = chapter_section.find(f'{NS}title')
            chapter_num = 0
            if chapter_title_elem is not None:
                chapter_text = get_text(chapter_title_elem)
                match = re.search(r'(\d+)', chapter_text)
                if match:
                    chapter_num = int(match.group(1))
            
            if chapter_num == 0:
                continue

            for p in chapter_section.findall(f'{NS}p'):
                text = get_text(p)
                if not text:
                    continue
                
                verse_match = re.match(r'^(\d+)[\s\xa0]+(.*)', text)
                if verse_match:
                    v_num = int(verse_match.group(1))
                    v_text = verse_match.group(2).strip()
                    
                    cursor.execute(
                        'INSERT INTO verses (book, book_order, chapter, verse_num, text) VALUES (?, ?, ?, ?, ?)',
                        (clean_name, order, chapter_num, v_num, v_text)
                    )
                    total_verses += 1

    conn.commit()
    print(f"Раздел обработан. Всего стихов: {total_verses}")

print(f"\n✅ Готово! Сохранено стихов: {total_verses}")

# Финальная проверка
